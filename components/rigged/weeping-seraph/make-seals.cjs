/* make-seals.cjs — the parts the halo seal is forged from.
   The seal itself is generated in the page by Sigil Forge's own generator
   (shared/generators/sigil-generator.js), so it can mutate forever; this picks the small set of
   creature parts it draws from, so the page does not carry all of creature-parts.json (1.8 MB).
   Light, line-drawn parts only: a few per role, chosen by a fixed hash so the set is stable.

     node components/rigged/weeping-seraph/make-seals.cjs     -> seraph-seal-parts.js (window.SERAPH_SEAL_PARTS) */
const fs = require("fs"), path = require("path");
const ROOT = path.resolve(__dirname, "../../..");
global.window = globalThis;
require(path.join(ROOT, "shared/generators/kit-utils.js"));
const K = window.ForgeKit;

const raw = JSON.parse(fs.readFileSync(path.join(ROOT, "shared/creature-parts.json"), "utf8"));
const parts = K.tagRoles(raw.parts || raw);
const ROLES = { blade: 14, hook: 12, rib: 6, lamp: 12, bead: 10, frieze: 10, segment: 10, spire: 8, halo: 8 };
const MAX = 3500;   // characters of SVG: keeps out the painted, filled parts
const lineOnly = (p) => !p.defs && /stroke="#/.test(p.svg) && !/stroke="none"/.test(p.svg);
const hash = (s) => { let h = 2166136261; for (const c of s) h = Math.imul(h ^ c.charCodeAt(0), 16777619); return h >>> 0; };

const keep = new Map();
for (const [role, n] of Object.entries(ROLES)) {
  const pool = parts.filter((p) => p.roles.includes(role) && p.svg.length <= MAX && lineOnly(p))
    .sort((a, b) => hash(role + a.id) - hash(role + b.id)).slice(0, n);
  for (const p of pool) keep.set(p.id, p);
}
// only what the generator reads; roles narrowed to the ones each part was picked for or already had
const out = [...keep.values()].map((p) => ({ id: p.id, w: p.w, h: p.h, svg: p.svg, roles: p.roles.filter((r) => r in ROLES) }));
const file = path.join(__dirname, "seraph-seal-parts.js");
fs.writeFileSync(file, "/* generated by make-seals.cjs from shared/creature-parts.json — do not edit */\nwindow.SERAPH_SEAL_PARTS = " + JSON.stringify(out) + ";\n");
console.log(out.length + " parts, " + (fs.statSync(file).size / 1024).toFixed(0) + " KB");
