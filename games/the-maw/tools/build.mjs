// Builds the TypeScript to the classic scripts the tank loads (shared/engine/ecology): eco-core.js (window.EcoCore) and
// maw-run.js (window.MawRun). Each is marked as built so nobody edits it in place.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
const out = (f) => fileURLToPath(new URL("../../../shared/engine/ecology/" + f, import.meta.url));
const head = (what, src) => `/* ${what}. BUILT from games/the-maw/${src} by \`npm run build\` there: do not edit this file. */`;
for (const [entry, file, what] of [["src/core/index.ts", "eco-core.js", "The simulation core (window.EcoCore): entity world, seeded random, clock, schedule"], ["src/run/index.ts", "maw-run.js", "The Maw's run layer (window.MawRun)"]])
  await build({ entryPoints: [entry], outfile: out(file), bundle: true, format: "iife", target: "es2020", banner: { js: head(what, entry) }, logLevel: "warning" });
console.log("built eco-core.js, maw-run.js");
