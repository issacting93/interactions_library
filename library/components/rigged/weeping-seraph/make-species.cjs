#!/usr/bin/env node
// Pull the creatures the Weeping Seraph's designs are made of out of Cybernetic Ecology's species file
// (shared/engine/ecology/ecology-species.js, ~20 MB for 40 species) into a small file the page can load.
// Data only: the geometry, rig parts and swim settings, unchanged; plus the seraph's five eye-ring
// drawings from the Kit (shared/data/creature-parts.json) for the wheel of eyes. Rerun after the ecology file changes:
//   node library/components/rigged/weeping-seraph/make-species.cjs
const fs = require("fs"), path = require("path");
// every creature a design on the page uses (front and back); keep in step with DESIGNS in weeping-seraph.html
const KEYS = ["halo-eyed-seraph", "ophan-halo-monarch", "carapace-strider", "glass-star", "crowned-sickle-lancer",
  "ringed-lance-monarch", "moth", "black-monarch", "eye-wing", "ringed-lance-swift-mk2", "jelly", "angler-tailed-jelly-af60"];
const src = path.join(__dirname, "../../../../shared/engine/ecology/ecology-species.js");
const window = {}; new Function("window", fs.readFileSync(src, "utf8"))(window);
const ES = window.EcologySpecies;
const picked = KEYS.map((k) => { const s = ES.SPECIES.find((x) => x.key === k); if (!s) throw new Error("not in ecology-species.js: " + k); return s; });
const EYES = ["P506", "P507", "P509", "P508", "P505"];
const kit = JSON.parse(fs.readFileSync(path.join(__dirname, "../../../../shared/data/creature-parts.json"), "utf8"));
const eyes = EYES.map((id) => { const p = kit.find((q) => q.id === id); if (!p) throw new Error("not in the Kit: " + id); return { id, svg: p.svg }; });
const out = `/* Generated by make-species.cjs from shared/engine/ecology/ecology-species.js. Do not edit by hand. */
window.SERAPH_SPECIES = ${JSON.stringify(picked)};
window.SERAPH_EYES = ${JSON.stringify(eyes)};
window.SERAPH_DEFAULT_COL_HI = ${JSON.stringify(ES.DEFAULT_COL_HI)};
`;
fs.writeFileSync(path.join(__dirname, "seraph-species.js"), out);
console.log("wrote seraph-species.js", (out.length / 1e6).toFixed(2) + " MB", KEYS.join(", "));
